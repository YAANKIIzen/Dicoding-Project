fun main() {
    val plat = "DM"

    when(plat){
        "A" -> {
            println("Plat A adalah plat Banten ")
        }
        "L" -> {
            println("Plat A adalah plat Surabaya ")
        }
        "DK" -> {
            println("Plat A adalah plat Bali ")
        }
        "DM" -> {
            println("Plat A adalah plat Gorontalo ")
        } else -> {
            println("Tidak ada plat kendaraannya")
        }
        
    }

    
}
//Hasilnya: Plat A adalah plat Gorontalo
